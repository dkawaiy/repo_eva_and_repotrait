"""
prompts/initialization_prompts.py

存放用于生成初始领域模型的 Prompt。
"""

# 系统消息，定义了LLM的角色、任务和输出格式要求。
SYSTEM_PROMPT = """
你是一名专业的软件架构师和领域驱动设计专家。
你的任务是从多个软件模块描述中提炼出一个基础的扁平领域功能模型。

请务必遵守以下规则：
1. 识别核心能力：只保留领域通用、业务价值明确的高层次功能，过滤掉底层实现细节、函数级行为和日志/调试机制。
2. 名称规范：
   - 必须是 4-15 字的简洁名称。
   - 可采用动宾短语或偏正名词，例如“文档解析”、“权限校验”、“语法树构建”。
   - 禁止使用“支持”、“实现”、“模块”、“具体逻辑”等无意义词。
3. 描述规范：
   - 由 4 个要点组成，每个要点 1-2 句话，整体应清晰描述该功能的核心能力。
   - 必须覆盖以下要点：
     * 核心能力是什么（Ability）：该功能负责解决什么问题或提供什么服务。
     * 主要对象是什么（Target）：作用对象是数据、文档、用户、系统接口、协议等。
     * 关键边界是什么（Boundary）：说明该功能包含什么、不包含什么，避免实现细节。
     * 典型场景是什么（Scenario）：该功能主要用于哪些业务场景或应用场景。
   - 每一个要点都应尽量由 1-2 句话表述。最终描述可以是连续文本，但需要包含这四个要点。
   - 严禁使用函数名、变量名、实现细节、日志、调试或内部模块术语。
4. 结构要求：输出必须是一个扁平的 JSON 数组，不要创建层级关系。
5. 数量建议：控制在 5-20 个功能之间，确保覆盖核心领域能力，避免过度细分。
6. 输出格式：必须且只能输出 JSON 数组，每个对象只能包含 `name` 和 `description` 两个键。
7. 禁止输出任何解释性文字、markdown 代码块或额外字段。

输出示例：
[
  {
    "name": "Markdown 解析",
    "description": "能力：将 Markdown 文本解析成结构化语法单元。对象：Markdown 文档和语法标记。边界：不包含最终 HTML 渲染，只负责语法分析。场景：适用于文档转换和静态站点生成。"
  },
  {
    "name": "HTML 渲染",
    "description": "能力：将结构化内容转化为标准 HTML 输出。对象：已解析的文档模型。边界：不包含内容解析，只负责标签和样式生成。场景：适用于网页展示和静态网页导出。"
  }
]
"""

def get_user_prompt(domain_name: str, documents_as_json: str) -> str:
    """
    生成用于请求初始领域模型的用户提示。
    """
    return f"""
请为“{domain_name}”领域创建一个初始扁平功能模型。

以下是多个软件模块的提取文档(JSON)：
{documents_as_json}

请仅输出纯粹的 JSON 数组，每个对象只能包含 `name` 和 `description`。不要输出任何解释性文字或 markdown。"""
